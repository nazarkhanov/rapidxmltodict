def sha(path):
    digest = hashlib.sha256()
    with Path(path).open("rb") as stream:
        for block in iter(lambda: stream.read(MIB), b""):
            digest.update(block)
    return digest.hexdigest()


def module(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    result = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(result)
    return result


def source_hashes(root):
    root = Path(root)
    files = [root / "setup.py", root / "pyproject.toml"]
    for folder in (root / "src", root / "vendor"):
        files.extend(path for path in folder.rglob("*") if path.is_file() and
                     path.suffix in (".py", ".pyi", ".cpp", ".hpp", ".h", ".so", ".pyd"))
    return {path.relative_to(root).as_posix(): sha(path) for path in sorted(files)}


def current_rss():
    for line in Path("/proc/self/status").read_text().splitlines():
        if line.startswith("VmRSS:"):
            return int(line.split()[1]) * 1024
    raise RuntimeError("This RSS benchmark requires Linux /proc/self/status")


def peak_rss():
    return resource.getrusage(resource.RUSAGE_SELF).ru_maxrss * (1 if sys.platform == "darwin" else 1024)


def available_memory():
    for line in Path("/proc/meminfo").read_text().splitlines():
        if line.startswith("MemAvailable:"):
            return int(line.split()[1]) * 1024
    raise RuntimeError("This memory guard requires Linux /proc/meminfo")


def pin_cpu(cpu=None):
    allowed = os.sched_getaffinity(0)
    selected = min(allowed) if cpu is None else cpu
    if selected not in allowed:
        raise ValueError("Requested CPU is outside the allowed CPU affinity")
    os.sched_setaffinity(0, {selected})
    return selected


def fingerprint(value):
    """Complete typed iterative traversal, including all string bytes.

    Unlike recursive equality or JSON serialization, this supports arbitrarily
    deep fixtures without raising Python's recursion limit. The iterator stack
    grows with nesting depth, not with the number of sibling records.
    """
    digest = hashlib.sha256()
    counts = {"dict": 0, "list": 0, "str": 0, "none": 0}
    def dictionary_pieces(value):
        for key in sorted(value):
            yield key
            yield value[key]

    stack = [(iter((value,)), False)]
    while stack:
        try:
            item = next(stack[-1][0])
        except StopIteration:
            _, closes_container = stack.pop()
            if closes_container:
                digest.update(b";")
            continue
        if isinstance(item, dict):
            counts["dict"] += 1
            digest.update(f"d{len(item)}:".encode())
            stack.append((dictionary_pieces(item), True))
        elif isinstance(item, list):
            counts["list"] += 1
            digest.update(f"l{len(item)}:".encode())
            stack.append((iter(item), True))
        elif isinstance(item, str):
            counts["str"] += 1
            digest.update(f"s{len(item)}:".encode())
            for offset in range(0, len(item), 65536):
                digest.update(item[offset:offset + 65536].encode("utf-8"))
            digest.update(b";")
        elif item is None:
            counts["none"] += 1
            digest.update(b"n:;")
        else:
            raise TypeError(f"Unsupported fingerprint type: {type(item).__name__}")
    return {"sha256": digest.hexdigest(), "type_counts": counts}


def resolve_entrypoint(entrypoint):
    name, symbol = entrypoint.split(":", 1)
    result = importlib.import_module(name)
    for part in symbol.split("."):
        result = getattr(result, part)
    return result


def verify_oracle():
    actual = importlib.metadata.version("xmltodict")
    if actual != ORACLE_VERSION:
        raise RuntimeError(f"Expected xmltodict {ORACLE_VERSION}; found {actual}")
    return actual


def worker(args):
    resource.setrlimit(resource.RLIMIT_AS, (args.limit_mib * MIB,) * 2)
    cpu = pin_cpu(args.cpu)
    verify_oracle()  # Metadata only: candidate workers do not import the oracle.
    parse = resolve_entrypoint(args.entrypoint)
    options = json.loads(args.options)
    source = Path(args.fixture)
    xml = source.open("rb") if args.parse_mode.endswith("file") else source.read_bytes()
    if args.parse_mode.endswith("str"):
        xml = xml.decode("utf-8")
    gc.enable()
    gc.collect()
    callback = args.parse_mode.startswith("callback_")
    retained_items = []
    callback_hash = hashlib.sha256()
    count = id_sum = id_square_sum = 0
    first_id = last_id = None

    def consume(path, item):
        nonlocal count, id_sum, id_square_sum, first_id, last_id
        identifier = int(item["@id"])
        first_id = identifier if first_id is None else first_id
        last_id = identifier
        count += 1
        id_sum += identifier
        id_square_sum += identifier * identifier
        if args.retain_callbacks:
            retained_items.append(item)
        if args.check_only:
            # Integrity pass is separate from measured callbacks. It hashes
            # every path and item without retaining their objects.
            path_value = [[name, attributes] for name, attributes in path]
            callback_hash.update(bytes.fromhex(fingerprint(path_value)["sha256"]))
            callback_hash.update(bytes.fromhex(fingerprint(item)["sha256"]))
        return True

    if callback:
        options.update(item_depth=2, item_callback=consume)
    baseline_current, baseline_peak = current_rss(), peak_rss()
    start = time.perf_counter_ns()
    output = parse(xml, **options)
    elapsed = time.perf_counter_ns() - start
    peak, retained = peak_rss(), current_rss()
    package = importlib.import_module("xmltodict" if args.variant == "xmltodict" else "rapidxmltodict")
    result = {
        "elapsed_ns": elapsed,
        "baseline_current_rss_bytes": baseline_current,
        "baseline_peak_rss_bytes": baseline_peak,
        "peak_rss_bytes": peak,
        "incremental_peak_rss_bytes": max(0, peak - baseline_peak),
        "retained_output_current_rss_bytes": retained,
        "retained_current_increase_bytes": retained - baseline_current,
        "parser_module_sha256": sha(package.__file__),
        "entrypoint": args.entrypoint,
        "cpu_affinity": [cpu],
        "gc_enabled": gc.isenabled(),
        "xmltodict_version": ORACLE_VERSION,
    }
    if args.variant != "xmltodict":
        result["loaded_extension_sha256"] = sha(importlib.import_module("rapidxmltodict._native").__file__)
    if callback:
        result["callback_summary"] = {
            "count": count, "id_sum": id_sum, "id_square_sum": id_square_sum,
            "first_id": first_id, "last_id": last_id,
            "parse_returned_none": output is None,
            "retained_items": len(retained_items),
        }
        if args.check_only:
            result["callback_content_sha256"] = callback_hash.hexdigest()
    else:
        # Crucially, RSS above was sampled before allocating fingerprint state.
        result["output_fingerprint"] = fingerprint(output)
    if args.standard_timing and not args.check_only:
        if callback or hasattr(xml, "read"):
            raise ValueError("Standard batches only support in-memory direct parsing")
        del output
        gc.collect()
        for _ in range(3):
            parse(xml, **options)
        start = time.perf_counter_ns()
        for _ in range(3):
            parse(xml, **options)
        estimate = (time.perf_counter_ns() - start) / 3
        loops = max(1, min(100000, round(args.batch_seconds * 1e9 / max(estimate, 1))))
        samples = []
        for _ in range(args.samples):
            start = time.perf_counter_ns()
            for _ in range(loops):
                parse(xml, **options)
            samples.append((time.perf_counter_ns() - start) / loops)
        result["timing"] = {"loops_per_batch": loops, "batch_ns_per_call": samples}
    if hasattr(xml, "close"):
        xml.close()
    return result


def make_fixtures(args):
    """Run only in the generator process, never a measured worker."""
    folder = Path(args.fixtures)
    folder.mkdir(parents=True, exist_ok=True)
    original_large = module("architecture_large_source", HERE / "upstream-large-memory.py")
    specs = []
    if args.suite in ("all", "standard"):
        original_standard = module("architecture_standard_source", HERE / "benchmark.py")
        original_standard.HERE = folder
        for spec in original_standard.create_fixtures():
            if spec["name"] in ("deep", "deep_fallback"):
                continue
            specs.append({**spec, "suite": "standard", "shape": spec["name"],
                          "parse_mode": "direct_" + spec["input_type"], "retain_callbacks": False})
        for depth in (128, 300, 1500, 10000):
            path = folder / f"deep-{depth}.xml"
            path.write_bytes(b"<n>" * depth + b"leaf" + b"</n>" * depth)
            specs.append({"name": f"deep_{depth}", "path": str(path), "suite": "standard",
                          "shape": "deep", "depth": depth, "bytes": path.stat().st_size,
                          "sha256": sha(path), "parse_mode": "direct_str", "retain_callbacks": False,
                          "description": f"{depth} nested elements, no recursion-limit adjustment"})
        for siblings in (6000, 60000):
            depth = 1500
            path = folder / f"late-deep-{siblings}-{depth}.xml"
            with path.open("wb") as stream:
                stream.write(b"<root>")
                for index in range(siblings):
                    stream.write((f'<item id="{index}"><name>Widget &amp; spare</name>'
                                  '<details><tag>alpha</tag><tag>beta</tag></details></item>').encode())
                stream.write(b"<branch>" + b"<n>" * depth + b"leaf" + b"</n>" * depth + b"</branch></root>")
            specs.append({"name": f"late_deep_{siblings}_siblings", "path": str(path), "suite": "standard",
                          "shape": "late_deep", "depth": depth + 2, "preceding_siblings": siblings,
                          "bytes": path.stat().st_size, "sha256": sha(path), "parse_mode": "direct_str",
                          "retain_callbacks": False, "description": "Deep branch after many completed shallow siblings"})
    if args.suite in ("all", "large"):
        for size in args.sizes:
            for shape in ("records", "large_text"):
                original = original_large.create_fixture(folder, shape, size)
                modes = [("direct_str", False), ("direct_file", False)]
                if shape == "records":
                    modes.extend([("callback_file", False), ("callback_file", True)])
                for mode, retain in modes:
                    suffix = ("_retain" if retain else "_discard") if mode.startswith("callback") else ""
                    specs.append({**original, "name": f"{shape}_{size}mib_{mode}{suffix}",
                                  "suite": "large", "parse_mode": mode, "retain_callbacks": retain,
                                  "input_type": "binary_file" if mode.endswith("file") else "str"})
    return specs


def sanitize_error(text, roots, fixture_root):
    # Do not publish local workspace roots, interpreter roots or user paths.
    replacements = {str(Path(root).resolve()): f"<{name}-snapshot>" for name, root in roots.items()}
    replacements[str(Path(fixture_root).resolve())] = "<fixtures>"
    replacements[str(HERE.resolve())] = "<benchmarks>"
    replacements[str(Path(sys.executable).parent.parent)] = "<python-environment>"
    for old, new in sorted(replacements.items(), key=lambda pair: len(pair[0]), reverse=True):
        text = text.replace(old, new)
    return text[-4000:]


def main(args):
    verify_oracle()
    if not all((args.baseline, args.iterative, args.native_events)):
        raise SystemExit("--baseline, --iterative and --native-events frozen source roots are required")
    roots = {"baseline": Path(args.baseline).resolve(), "iterative_dom": Path(args.iterative).resolve(),
             "native_events": Path(args.native_events).resolve()}
    entries = {"baseline": "rapidxmltodict:parse", "iterative_dom": args.iterative_entrypoint,
               "native_events": args.events_entrypoint, "xmltodict": "xmltodict:parse"}
    options = {"baseline": "{}", "iterative_dom": args.iterative_options,
               "native_events": args.events_options, "xmltodict": "{}"}
    for value in options.values():
        if not isinstance(json.loads(value), dict):
            raise SystemExit("Entry point options must be JSON objects")
    output = Path(args.output)
    output.parent.mkdir(parents=True, exist_ok=True)
    cpu = pin_cpu(args.cpu)
    hashes_start = {name: source_hashes(root) for name, root in roots.items()}
    import xmltodict
    cpu_model = next((line.split(":", 1)[1].strip() for line in Path("/proc/cpuinfo").read_text().splitlines()
                      if line.startswith("model name")), platform.processor())
    metadata = {
        "timestamp_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "python": sys.version, "platform": platform.platform(), "cpu": cpu_model, "cpu_affinity": [cpu],
        "compiler": subprocess.check_output(["g++", "--version"], text=True).splitlines()[0],
        "build_flags": "CC=gcc CXX=g++; setup.py build_ext --inplace --force; -O3 -std=c++17 -Wall -Wextra",
        "baseline_commit": BASELINE_COMMIT,
        "iterative_commit": args.iterative_commit,
        "native_events_commit": args.native_events_commit,
        "baseline_provenance_note": "Frozen pre-prototype source and existing binary. The pre-existing vendor-header CRLF/LF difference from the Git checkout is preserved and separately disclosed; hashes identify the exact measured bytes.",
        "source_and_binary_hashes_start": hashes_start,
        "comparison_variants": VARIANTS, "entrypoints": entries,
        "entrypoint_options": {name: json.loads(value) for name, value in options.items()},
        "variant_descriptions": {
            "baseline": "Current integrated e911 baseline public parse; existing depth limit may trigger a second event parse.",
            "iterative_dom": "Iterative DOM/default public parse: iterative DOM for default in-memory str/bytes, existing Python event mapping for file/callback/options.",
            "native_events": "Private direct native-event dictionary mapper, forced via the recorded wrapper entry point.",
            "xmltodict": "Unmodified xmltodict 1.0.4 public parse, Expat reference.",
        },
        "xmltodict_version": ORACLE_VERSION, "xmltodict_source_sha256": sha(xmltodict.__file__),
        "harness_sha256": sha(__file__),
        "fixture_generator_hashes": {name: sha(HERE / name) for name in ("benchmark.py", "upstream-large-memory.py")},
        "initial_available_memory_bytes": available_memory(),
        "method": {
            "suite": args.suite, "repetitions": args.repetitions, "fresh_process_per_sample": True,
            "cpu_pinned": True, "pythonhashseed": "0", "gc_enabled": True,
            "input_generation": "Separate generator process, all fixtures generated before all measured workers.",
            "ordering": "Balanced rotating variant order, offset by workload index and repetition.",
            "standard_timing": {"warmup_calls": 3, "calibration_calls": 3, "batches_per_process": args.samples,
                                "target_batch_seconds": args.batch_seconds, "output_destruction_timed": True},
            "standard_rss": "First parse in each fresh sample worker; sampled before fingerprint and before warmed timing batches.",
            "large_timing": "One parse per fresh process; output destruction and fixture loading excluded; file reading included.",
            "rss": "Linux current RSS and ru_maxrss, post-import/post-input baseline, total peak, peak minus baseline high-water mark, and retained current RSS. Input and output remain alive at sample.",
            "incremental_peak_caveat": "Incremental peak subtracts baseline high-water RSS, not current baseline RSS; a previous input-loading peak can make incremental growth look small.",
            "callbacks": "Same item_depth=2 callback tracks count/order/identifier sums. Discard retains no items; retain stores every item until RSS sample. File streams read through the normal wrapper.",
            "correctness": "Complete typed iterative fingerprints for direct outputs. Separate unmeasured callback integrity workers hash every path and item. Measured callbacks validate full count and identifier checksums.",
            "max_address_space_mib": args.limit_mib,
            "memory_guard": "Skip estimated peak over 40% MemAvailable or 80% RLIMIT_AS; stop on worker failure, no automatic OOM retry.",
            "private_prototype": True,
        },
    }
    expat_data = subprocess.check_output([sys.executable, "-c", "import json,pyexpat; print(json.dumps({'version':pyexpat.EXPAT_VERSION,'version_info':pyexpat.version_info,'features':pyexpat.features}))"], text=True)
    metadata["reference_expat_provenance"] = json.loads(expat_data)
    data = {"schema_version": 1, "metadata": metadata, "workloads": {}, "run_order": []}
    command = [sys.executable, str(Path(__file__).resolve()), "--generate", "--fixtures", args.fixtures,
               "--suite", args.suite, "--sizes", *map(str, args.sizes)]
    specs = json.loads(subprocess.check_output(command, text=True, close_fds=False))
    if args.workloads:
        requested = set(args.workloads)
        known = {spec["name"] for spec in specs}
        if requested - known:
            raise SystemExit(f"Unknown workloads: {sorted(requested - known)}")
        specs = [spec for spec in specs if spec["name"] in requested]
        metadata["workload_subset"] = list(args.workloads)

    def save():
        output.write_text(json.dumps(data, indent=2) + "\n")

    def run(spec, variant, check=False):
        env = os.environ.copy()
        env["PYTHONHASHSEED"] = "0"
        if variant == "xmltodict":
            env.pop("PYTHONPATH", None)
        else:
            env["PYTHONPATH"] = str(roots[variant] / "src")
        command = [sys.executable, str(Path(__file__).resolve()), "--worker", "--variant", variant,
                   "--entrypoint", entries[variant], "--options", options[variant],
                   "--fixture", spec["path"], "--parse-mode", spec["parse_mode"],
                   "--cpu", str(cpu), "--limit-mib", str(args.limit_mib), "--samples", str(args.samples),
                   "--batch-seconds", str(args.batch_seconds)]
        if check:
            command.append("--check-only")
        elif spec["suite"] == "standard":
            command.append("--standard-timing")
        if spec["retain_callbacks"] and not check:
            command.append("--retain-callbacks")
        try:
            child = subprocess.run(command, env=env, capture_output=True, text=True, close_fds=False, timeout=args.timeout)
        except subprocess.TimeoutExpired:
            return {"worker_failed": True, "reason": "Worker exceeded the configured timeout",
                    "timeout_seconds": args.timeout}
        if child.returncode:
            return {"worker_failed": True, "returncode": child.returncode,
                    "stderr": sanitize_error(child.stderr, roots, args.fixtures)}
        result = json.loads(child.stdout)
        if variant != "xmltodict":
            expected_extension = [digest for name, digest in hashes_start[variant].items()
                                  if "/_native" in name and name.endswith((".so", ".pyd"))]
            if result["loaded_extension_sha256"] not in expected_extension:
                raise RuntimeError(f"{variant}: worker imported an unexpected extension")
        return result

    try:
        for index, spec in enumerate(specs):
            name = spec["name"]
            entry = {key: value for key, value in spec.items() if key != "path"}
            entry.update(samples={variant: [] for variant in VARIANTS}, skipped={})
            data["workloads"][name] = entry
            callback = spec["parse_mode"].startswith("callback")
            if callback:
                prior_integrity = next((previous for previous in data["workloads"].values()
                    if previous is not entry and previous.get("sha256") == spec["sha256"]
                    and previous.get("parse_mode") == spec["parse_mode"]
                    and previous.get("all_callback_content_equal")), None)
                entry["callback_integrity"] = {}
                if prior_integrity is not None:
                    entry["callback_integrity"] = prior_integrity["callback_integrity"]
                    entry["callback_integrity_reused_from"] = prior_integrity["name"]
                for variant in (() if prior_integrity is not None else VARIANTS):
                    check = run(spec, variant, check=True)
                    if check.get("worker_failed"):
                        entry["skipped"][variant] = check
                        save()
                        raise RuntimeError(f"{name}/{variant}: integrity worker failed; see saved result")
                    entry["callback_integrity"][variant] = {
                        "callback_content_sha256": check["callback_content_sha256"],
                        "callback_summary": check["callback_summary"],
                    }
                digests = {value["callback_content_sha256"] for value in entry["callback_integrity"].values()}
                entry["all_callback_content_equal"] = len(digests) == 1
                if not entry["all_callback_content_equal"]:
                    raise RuntimeError(f"{name}: complete callback content differs from xmltodict")
            for repetition in range(args.repetitions):
                rotation = (index + repetition) % len(VARIANTS)
                order = VARIANTS[rotation:] + VARIANTS[:rotation]
                for variant in order:
                    available = available_memory()
                    estimate = 128 * MIB if callback and not spec["retain_callbacks"] else spec["bytes"] * (24 if spec["shape"] != "large_text" else 8) + 64 * MIB
                    prior = [item for item in data["workloads"].values() if item["shape"] == spec["shape"] and
                             item["parse_mode"] == spec["parse_mode"] and item["retain_callbacks"] == spec["retain_callbacks"]
                             and item["bytes"] < spec["bytes"] and item["samples"][variant]]
                    if prior and not (callback and not spec["retain_callbacks"]):
                        previous = max(prior, key=lambda item: item["bytes"])
                        ratio = max(sample["peak_rss_bytes"] for sample in previous["samples"][variant]) / previous["bytes"]
                        estimate = spec["bytes"] * ratio * 1.25 + 64 * MIB
                    if estimate > min(available * 0.4, args.limit_mib * MIB * 0.8):
                        entry["skipped"][variant] = {"reason": "Conservative memory budget exceeded",
                                                     "estimated_peak_bytes": estimate, "available_memory_bytes": available}
                        save()
                        continue
                    sample = run(spec, variant)
                    data["run_order"].append({"workload": name, "repetition": repetition, "variant": variant,
                                              "available_memory_bytes": available})
                    if sample.get("worker_failed"):
                        entry["skipped"][variant] = sample
                        save()
                        raise RuntimeError(f"{name}/{variant}: worker failed; see saved result")
                    entry["samples"][variant].append(sample)
                    print(f'{name} {variant} #{repetition + 1}: {sample["elapsed_ns"] / 1e9:.4f}s; peak {sample["peak_rss_bytes"] / MIB:.1f} MiB; retained {sample["retained_output_current_rss_bytes"] / MIB:.1f} MiB', flush=True)
                    save()
            if callback:
                count = spec["records"]
                expected = {"count": count, "id_sum": count * (count - 1) // 2,
                            "id_square_sum": count * (count - 1) * (2 * count - 1) // 6,
                            "first_id": 0, "last_id": count - 1, "parse_returned_none": True,
                            "retained_items": count if spec["retain_callbacks"] else 0}
                entry["expected_callback_summary"] = expected
                entry["all_callback_summaries_equal"] = all(sample["callback_summary"] == expected
                    for samples in entry["samples"].values() for sample in samples)
                if not entry["all_callback_summaries_equal"]:
                    raise RuntimeError(f"{name}: callback count/order checksum mismatch")
            else:
                digests = {sample["output_fingerprint"]["sha256"] for samples in entry["samples"].values() for sample in samples}
                entry["all_output_fingerprints_equal"] = len(digests) == 1
                if len(digests) > 1:
                    raise RuntimeError(f"{name}: complete output differs from xmltodict")
            entry["medians"] = {}
            for variant, samples in entry["samples"].items():
                if not samples:
                    continue
                medians = {metric: statistics.median(sample[metric] for sample in samples) for metric in METRICS}
                timings = [value for sample in samples for value in sample.get("timing", {}).get("batch_ns_per_call", [sample["elapsed_ns"]])]
                medians.update(timing_median_ns=statistics.median(timings), timing_min_ns=min(timings), timing_max_ns=max(timings))
                entry["medians"][variant] = medians
            save()
        metadata["all_requested_samples_completed"] = all(len(samples) == args.repetitions
            for entry in data["workloads"].values() for samples in entry["samples"].values())
    finally:
        metadata["source_and_binary_hashes_end"] = {name: source_hashes(root) for name, root in roots.items()}
        metadata["source_and_binary_hashes_unchanged"] = hashes_start == metadata["source_and_binary_hashes_end"]
        metadata["finished_utc"] = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
        save()
    if not metadata["source_and_binary_hashes_unchanged"]:
        raise RuntimeError("Source or binary changed during measurement; this result is invalid")


